// Converts links.json + accounting/*.csv into CSV files for n8n Data Tables import.
// No dependencies. Output: systems/n8n/seed/out/ (gitignored). Usage: node systems/n8n/seed/seed.js
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '../../..'), OUT = path.join(__dirname, 'out');
const TABLES = path.join(ROOT, 'systems/n8n/tables');

// Forbidden column names (guest data, tap times, device/IP). host_/worker_/clients.whatsapp are allowed
// by the spec but must stay EMPTY in seed (see MUST_BE_EMPTY).
const FORBIDDEN = /phone|mobile|msisdn|jawal|^guest|_guest|guest_|^ip$|_ip$|^ip_|ip_addr|user_agent|wa_id|sender|last_tap|tap_time|touched_at/i;
const MUST_BE_EMPTY = { clients: ['whatsapp'], unit_contacts: ['host_whatsapp', 'worker_whatsapp'] };

// Normalise: Arabic-Indic and Persian digits -> ASCII, drop spaces/dashes/dots/brackets.
function normDigits(v) {
  return String(v ?? '')
    .replace(/[٠-٩]/g, d => String(d.charCodeAt(0) - 0x0660))
    .replace(/[۰-۹]/g, d => String(d.charCodeAt(0) - 0x06F0))
    .replace(/[\s\-‐-―().\[\]‎‏ ]/g, '');
}
// Saudi mobile: 05xxxxxxxx, 5xxxxxxxx, +9665xxxxxxxx, 009665xxxxxxxx, 9665xxxxxxxx
// Prefixed forms (05.., +966/00966/966 5..) are checked in every column.
// Bare 9-digit 5xxxxxxxx is checked only in free-text columns: ID/number columns
// (bank_ref, invoice_no, entry_no, payment_ref, reference, code, ref, account_code) may legitimately hold such digits.
const PHONE_PREFIXED = /(?:^|\D)(?:\+?966|00966|0)5\d{8}(?:\D|$)/;
const PHONE_BARE9 = /(?:^|\D)5\d{8}(?:\D|$)/;
const ID_COLS = new Set(['bank_ref', 'invoice_no', 'entry_no', 'payment_ref', 'reference', 'code', 'ref', 'account_code']);
const looksLikePhone = (v, col = '') => { const n = normDigits(v); return PHONE_PREFIXED.test(n) || (!ID_COLS.has(col) && PHONE_BARE9.test(n)); };

fs.mkdirSync(OUT, { recursive: true });

function parseCSV(txt) {
  const rows = []; let row = [], f = '', q = false;
  for (let i = 0; i < txt.length; i++) {
    const c = txt[i];
    if (q) { if (c === '"') { if (txt[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c; }
    else if (c === '"') q = true; else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && txt[i + 1] === '\n') i++; row.push(f); rows.push(row); row = []; f = ''; }
    else f += c;
  }
  if (f !== '' || row.length) { row.push(f); rows.push(row); }
  return rows.filter(r => r.some(x => x.trim() !== ''));
}
const esc = v => { v = v == null ? '' : String(v); return /[",\r\n]/.test(v) ? '"' + v.replace(/"/g, '""') + '"' : v; };
const schemaCols = t => JSON.parse(fs.readFileSync(path.join(TABLES, t + '.json'), 'utf8')).columns.map(c => c.name);

function write(t, rows) {
  const cols = schemaCols(t);
  for (const c of cols) if (FORBIDDEN.test(c)) throw new Error(`forbidden column ${t}.${c}`);
  const lines = [cols.join(',')];
  for (const r of rows) {
    for (const c of MUST_BE_EMPTY[t] || []) if (String(r[c] ?? '').trim()) throw new Error(`${t}.${c} must be empty in seed`);
    const vals = cols.map(c => r[c]);
    vals.forEach((v, i) => { if (looksLikePhone(v, cols[i])) throw new Error(`phone-like value in ${t}.${cols[i]}`); });
    lines.push(vals.map(esc).join(','));
  }
  fs.writeFileSync(path.join(OUT, t + '.csv'), lines.join('\r\n') + '\r\n');
  console.log(`${t}.csv  rows=${rows.length}  cols=${cols.length}`);
}
const readCSV = f => {
  const rows = parseCSV(fs.readFileSync(f, 'utf8').replace(/^﻿/, ''));
  const head = rows.shift() || [];
  return { head, rows: rows.map(r => Object.fromEntries(head.map((h, i) => [h, r[i] ?? '']))) };
};

// units + clients from links.json (ref copied from links.json for door units; generated only by links-cli.js add --type door)
const links = JSON.parse(fs.readFileSync(path.join(ROOT, 'systems/shortlinks/links.json'), 'utf8'));
write('units', links.map(l => ({ code: l.code, ref: l.type === 'door' ? (l.ref || '') : '', client_id: l.client || '', place: l.place, dest: l.dest,
  type: l.type === 'door' ? 'door' : 'public', status: l.status, programmed: l.programmed })));
const clientIds = [...new Set(links.map(l => l.client).filter(Boolean))];
write('clients', clientIds.map(id => ({ client_id: id, whatsapp: '',
  status: links.some(l => l.client === id && l.status === 'active') ? 'active' : 'cancelled' })));

// invoices, payments: header must equal schema exactly
for (const t of ['invoices', 'payments']) {
  const { head, rows } = readCSV(path.join(ROOT, 'accounting', t + '.csv'));
  if (head.join(',') !== schemaCols(t).join(',')) throw new Error(`${t}: header mismatch\n csv:    ${head}\n schema: ${schemaCols(t)}`);
  write(t, rows);
}
// ledger: schema = csv columns + line_no (generated by order within entry_no)
{
  const { head, rows } = readCSV(path.join(ROOT, 'accounting/ledger.csv'));
  const expect = schemaCols('ledger').filter(c => c !== 'line_no');
  if (head.join(',') !== expect.join(',')) throw new Error(`ledger: header mismatch\n csv:    ${head}\n schema: ${expect}`);
  const n = {};
  write('ledger', rows.map(r => ({ ...r, line_no: (n[r.entry_no] = (n[r.entry_no] || 0) + 1) })));
}
// empty templates (unit_contacts stays empty before launch)
for (const t of ['subscriptions', 'unit_contacts', 'prospects', 'daily_taps']) write(t, []);

// self-test of the phone detector (fails loudly if the regex regresses)
const bad = ['0551234567', '551234567', '+966551234567', '00966551234567', '٠٥٥١٢٣٤٥٦٧', '055 123 4567', '(055)-123-4567'];
if (!looksLikePhone('512345678', 'notes') || looksLikePhone('512345678', 'bank_ref')) throw new Error('bare-9 rule broken');
const ok = ['2026-09-27', 'INV-0001', '1100', 'demo01', 'https://example.com/menu'];
for (const s of bad) if (!looksLikePhone(s)) throw new Error('phone detector missed: ' + s);
for (const s of ok) if (looksLikePhone(s)) throw new Error('phone detector false positive: ' + s);
console.log('phone detector self-test: ok');
